"""Write binding_api.usda: MaterialBindingAPI on the Sponza add-ons' meshes.

  hython tests/scenes/production/make_binding_api.py

The curtains, ivy, cypress, candles and knight packages author material:binding without applying
MaterialBindingAPI. Hydra 2.0 reads bindings through that schema only, so Karma and Eldr would render
those meshes with their displayColor. The layer applies it with overs (no other opinions); the views
sublayer it. The knight's meshes are under /knight/geo, where sponza_knight.usda references it.
"""
import os
from pxr import Sdf, Usd, UsdShade

ROOT = "E:/usd-testscenes/sponza/"
PACKAGES = [("pkg_a_curtains/NewSponza_Curtains_USD_ZUp.usda", None),
            ("pkg_b_ivy/NewSponza_IvyGrowth_USD_ZUp.usda", None),
            ("pkg_c_trees/NewSponza_CypressTree_USDA_ZUp.usda", None),
            ("pkg_d_10k_candles/NewSponza_4_Combined_USDA_ZUp.usda", None),
            ("pkg_e_knight_anim/knight_USD_PREVIEW_SURFACE_ANIM_002_1.usd", ("/knight_rig_Geometry", "/knight/geo"))]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "binding_api.usda")


def main():
    out = Sdf.Layer.CreateAnonymous(".usda")
    for path, remap in PACKAGES:
        stage = Usd.Stage.Open(ROOT + path)
        for prim in stage.Traverse():
            if prim.GetRelationship("material:binding") and not prim.HasAPI(UsdShade.MaterialBindingAPI):
                p = prim.GetPath()
                if remap:
                    if not p.HasPrefix(remap[0]):
                        continue
                    p = p.ReplacePrefix(Sdf.Path(remap[0]), Sdf.Path(remap[1]))
                spec = Sdf.CreatePrimInLayer(out, p)
                spec.SetInfo("apiSchemas", Sdf.TokenListOp.Create(prependedItems=["MaterialBindingAPI"]))
    out.Export(OUT, comment="Generated by make_binding_api.py")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
